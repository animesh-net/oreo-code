#!/usr/bin/env bash
# Checks scripts/clean_pr_body.py: footers and trailers go, everything else stays.
set -euo pipefail
cd "$(dirname "$0")"

body=$'## What changed\n\n- Adds a check.\n\n## Checklist\n\n- [x] No `Co-Authored-By` or AI attribution in commits or this description\n'
fail=0

expect() { # name, input, expected output, expected exit code
  local out status=0
  out=$(printf '%s' "$2" | python3 -I clean_pr_body.py) || status=$?
  if [ "$out" != "$3" ] || [ "$status" -ne "$4" ]; then
    echo "FAIL: $1 (exit $status)"
    fail=1
  fi
}

clean=${body%$'\n'}
expect "a clean body is unchanged" "$body" "$clean" 0
expect "a generated-by footer and its rule go" "$body"$'\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01ABC)_\n' "$clean" 1
expect "a generated-with footer and session link go" "$body"$'\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01ABC\n' "$clean" 1
expect "co-author lines go" $'Fix the check\n\nCo-authored-by: Someone <a@b.c>\n' "Fix the check" 1
expect "Windows line endings" "${body//$'\n'/$'\r\n'}"$'\r\n---\r\n_Generated by [Claude Code](https://claude.ai/code)_' "$clean" 1

[ "$fail" -eq 0 ] && echo "PASS: PR description cleaner"
exit "$fail"
